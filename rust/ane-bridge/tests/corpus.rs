//! Real-world-ish MIL corpus: opens a small set of varied MIL programs
//! through the full `Model::open` → `modelAttributes` derivation path,
//! and asserts the parser produces specs consistent with the declared
//! MIL signature.
//!
//! This catches:
//!   * `modelAttributes` shapes we haven't anticipated in the parser
//!     (e.g., a new dtype, a different procedure layout, a depth > 1
//!     tensor that exercises the 5-D rank branch);
//!   * Loss of fidelity between the MIL we feed and what the parser
//!     reports back through `Model::input`/`Model::output`;
//!   * Compile/load failures on shapes that should be accepted.
//!
//! The MIL strings are hand-built rather than generated by
//! `coremltools` — keeps the test self-contained and reproducible
//! across machines without a Python dep.

