/// Identity-style MIL: `y = cast(fp32, cast(fp16, x))` with caller-
/// chosen input/output dtype + shape declared in the func signature.
fn build_identity_mil(token: &str, dtype: &str, shape: &[i64]) -> String {
    let shape_str = shape
        .iter()
        .map(ToString::to_string)
        .collect::<Vec<_>>()
        .join(", ");
    format!(
        r#"program(1.3)
[buildInfo = dict<string, string>({{{{"coremlc-component-MIL", "3510.2.1"}}, {{"coremlc-version", "3505.4.1"}}, {{"coremltools-component-milinternal", ""}}, {{"coremltools-version", "9.0"}}, {{"ane-bridge-corpus", "{token}"}}}})]
{{
    func main<ios18>(tensor<{dtype}, [{shape_str}]> x) {{
        string td16 = const()[name = string("td16"), val = string("fp16")];
        tensor<fp16, [{shape_str}]> x16 = cast(dtype = td16, x = x)[name = string("x16")];
        string td_out = const()[name = string("td_out"), val = string("{dtype}")];
        tensor<{dtype}, [{shape_str}]> y = cast(dtype = td_out, x = x16)[name = string("y")];
    }} -> (y);
}}
"#
    )
}

/// Dual-input dual-output identity: `ya = id(a)`, `yb = id(b)`. Shapes
/// can differ between the two pairs.
fn build_dual_io_mil(token: &str, shape_a: &[i64], shape_b: &[i64]) -> String {
    let sa = shape_a
        .iter()
        .map(ToString::to_string)
        .collect::<Vec<_>>()
        .join(", ");
    let sb = shape_b
        .iter()
        .map(ToString::to_string)
        .collect::<Vec<_>>()
        .join(", ");
    format!(
        r#"program(1.3)
[buildInfo = dict<string, string>({{{{"coremlc-component-MIL", "3510.2.1"}}, {{"coremlc-version", "3505.4.1"}}, {{"coremltools-component-milinternal", ""}}, {{"coremltools-version", "9.0"}}, {{"ane-bridge-corpus", "{token}"}}}})]
{{
    func main<ios18>(tensor<fp32, [{sa}]> a, tensor<fp32, [{sb}]> b) {{
        string td16 = const()[name = string("td16"), val = string("fp16")];
        tensor<fp16, [{sa}]> a16 = cast(dtype = td16, x = a)[name = string("a16")];
        tensor<fp16, [{sb}]> b16 = cast(dtype = td16, x = b)[name = string("b16")];
        string td32 = const()[name = string("td32"), val = string("fp32")];
        tensor<fp32, [{sa}]> ya = cast(dtype = td32, x = a16)[name = string("ya")];
        tensor<fp32, [{sb}]> yb = cast(dtype = td32, x = b16)[name = string("yb")];
    }} -> (ya, yb);
}}
"#
    )
}

/// Write the given MIL + a placeholder weights blob to a fresh
/// tempdir and return the paths.
fn write_fixture(mil: &str) -> Fixture {
    let dir = tempfile::tempdir().expect("tempdir");
    let mil_path = dir.path().join("model.mil");
    let wts_path = dir.path().join("weights.bin");
    std::fs::write(&mil_path, mil).expect("write MIL");
    std::fs::write(&wts_path, b"\x00").expect("write weights");
    Fixture {
        _dir: dir,
        mil: mil_path,
        weights: wts_path,
    }
}

#[derive(Clone)]
struct Case {
    label: &'static str,
    mil: String,
    expected_inputs: Vec<(&'static str, Dtype, Vec<i64>)>,
    expected_outputs: Vec<(&'static str, Dtype, Vec<i64>)>,
}

fn corpus() -> Vec<Case> {
    use Dtype::{Fp16, Fp32};
    let mut tok = 0_u32;
    let mut next_token = || {
        tok += 1;
        format!("corpus-{tok}")
    };

    vec![
        Case {
            label: "fp32-1x64x1x16",
            mil: build_identity_mil(&next_token(), "fp32", &[1, 64, 1, 16]),
            expected_inputs: vec![("x", Fp32, vec![1, 64, 1, 16])],
            expected_outputs: vec![("y", Fp32, vec![1, 64, 1, 16])],
        },
        Case {
            label: "fp16-1x64x1x16",
            mil: build_identity_mil(&next_token(), "fp16", &[1, 64, 1, 16]),
            expected_inputs: vec![("x", Fp16, vec![1, 64, 1, 16])],
            expected_outputs: vec![("y", Fp16, vec![1, 64, 1, 16])],
        },
        Case {
            label: "fp32-2x32x4x32",
            mil: build_identity_mil(&next_token(), "fp32", &[2, 32, 4, 32]),
            expected_inputs: vec![("x", Fp32, vec![2, 32, 4, 32])],
            expected_outputs: vec![("y", Fp32, vec![2, 32, 4, 32])],
        },
        Case {
            label: "fp32-1x16x1x16-tall-channel",
            mil: build_identity_mil(&next_token(), "fp32", &[1, 16, 1, 16]),
            expected_inputs: vec![("x", Fp32, vec![1, 16, 1, 16])],
            expected_outputs: vec![("y", Fp32, vec![1, 16, 1, 16])],
        },
        Case {
            label: "dual-io-same-shape",
            mil: build_dual_io_mil(&next_token(), &[1, 64, 1, 16], &[1, 64, 1, 16]),
            expected_inputs: vec![
                ("a", Fp32, vec![1, 64, 1, 16]),
                ("b", Fp32, vec![1, 64, 1, 16]),
            ],
            expected_outputs: vec![
                ("ya", Fp32, vec![1, 64, 1, 16]),
                ("yb", Fp32, vec![1, 64, 1, 16]),
            ],
        },
        Case {
            label: "dual-io-asymmetric",
            mil: build_dual_io_mil(&next_token(), &[1, 32, 1, 16], &[1, 64, 1, 8]),
            expected_inputs: vec![
                ("a", Fp32, vec![1, 32, 1, 16]),
                ("b", Fp32, vec![1, 64, 1, 8]),
            ],
            expected_outputs: vec![
                ("ya", Fp32, vec![1, 32, 1, 16]),
                ("yb", Fp32, vec![1, 64, 1, 8]),
            ],
        },
    ]
}

#[test]
fn corpus_matches_framework_schema() {
    let cases = corpus();
    for case in cases {
        let fx = write_fixture(&case.mil);
        let opts = OpenOptions::new(fx.mil_path(), fx.weights_path());
        let model = match Model::open(&opts) {
            Ok(m) => m,
            Err(e) => {
                // Compile/Load failures here mean the *framework*
                // rejected the MIL — not a parser bug, but worth
                // surfacing in the test report.
                panic!("[{}] Model::open failed: {e}", case.label);
            }
        };
        let nin = usize::try_from(model.num_inputs()).expect("non-negative input count");
        let nout = usize::try_from(model.num_outputs()).expect("non-negative output count");
        assert_eq!(
            nin,
            case.expected_inputs.len(),
            "[{}] input count: got {nin}, want {}",
            case.label,
            case.expected_inputs.len(),
        );
        assert_eq!(
            nout,
            case.expected_outputs.len(),
            "[{}] output count: got {nout}, want {}",
            case.label,
            case.expected_outputs.len(),
        );
        for (i, (name, dt, shape)) in case.expected_inputs.iter().enumerate() {
            let idx = i32::try_from(i).expect("input index fits in i32");
            let got = model
                .input(idx)
                .unwrap_or_else(|| panic!("[{}] input {i} missing", case.label));
            assert_eq!(got.name(), *name, "[{}] input {i} name", case.label);
            assert_eq!(got.dtype(), *dt, "[{}] input {i} dtype", case.label);
            assert_eq!(got.shape(), &shape[..], "[{}] input {i} shape", case.label);
        }
        for (i, (name, dt, shape)) in case.expected_outputs.iter().enumerate() {
            let idx = i32::try_from(i).expect("output index fits in i32");
            let got = model
                .output(idx)
                .unwrap_or_else(|| panic!("[{}] output {i} missing", case.label));
            assert_eq!(got.name(), *name, "[{}] output {i} name", case.label);
            assert_eq!(got.dtype(), *dt, "[{}] output {i} dtype", case.label);
            assert_eq!(got.shape(), &shape[..], "[{}] output {i} shape", case.label);
        }
    }
}
